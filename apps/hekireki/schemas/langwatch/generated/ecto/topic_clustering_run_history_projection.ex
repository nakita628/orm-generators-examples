defmodule LangWatch.TopicClusteringRunHistoryProjection do
  @moduledoc """
  Per-project topic clustering run history (audit read model, ADR-051).
  One row per project; `runs` is the bounded newest-first entry list.
  Rebuildable by replaying the event log.
  """

  use Ecto.Schema

  @primary_key false

  @type t :: %__MODULE__{
          id: String.t(),
          project_id: String.t(),
          runs: map() | list() | String.t() | number() | boolean(),
          created_at: float(),
          updated_at: float(),
          occurred_at: float(),
          accepted_at: float(),
          last_event_id: String.t(),
          projection_version: String.t()
        }

  schema "TopicClusteringRunHistoryProjection" do
    # KSUID (`topicrunhist_…`), generated by the repository on first upsert.
    field(:id, :string, primary_key: true)
    field(:project_id, :string, source: :projectId)
    field(:runs, LangWatch.PrismaJson)
    field(:created_at, :float, source: :createdAt)
    field(:updated_at, :float, source: :updatedAt)
    # Business time of the latest applied event.
    field(:occurred_at, :float, source: :occurredAt)
    # Event-log acceptance time. Together with lastEventId this is the cursor.
    field(:accepted_at, :float, source: :acceptedAt)
    field(:last_event_id, :string, source: :lastEventId)
    field(:projection_version, :string, source: :projectionVersion)
  end
end