defmodule LangWatch.TopicModelProjection do
  @moduledoc """
  Cursor row for the topic-model projection (ADR-051). The model itself is
  the `Topic` table, written through by the projection; this row only
  records how far the fold has applied the event log.
  """

  use Ecto.Schema

  @primary_key false

  @type t :: %__MODULE__{
          id: String.t(),
          project_id: String.t(),
          created_at: float(),
          updated_at: float(),
          occurred_at: float(),
          accepted_at: float(),
          last_event_id: String.t(),
          projection_version: String.t()
        }

  schema "TopicModelProjection" do
    # KSUID (`topicmodel_…`), generated by the repository on first upsert.
    field(:id, :string, primary_key: true)
    field(:project_id, :string, source: :projectId)
    field(:created_at, :float, source: :createdAt)
    field(:updated_at, :float, source: :updatedAt)
    # Business time of the latest applied event.
    field(:occurred_at, :float, source: :occurredAt)
    # Event-log acceptance time. Together with lastEventId this is the cursor.
    field(:accepted_at, :float, source: :acceptedAt)
    field(:last_event_id, :string, source: :lastEventId)
    field(:projection_version, :string, source: :projectionVersion)
  end
end