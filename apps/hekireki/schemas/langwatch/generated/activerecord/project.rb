# legacyApiKeyLastUsedAt:: When the legacy apiKey last authenticated a request, written at most once a
#   minute per project and process. Spec: modules/api-key/specs/request-credential-type.feature
# lwqlKey:: Random per-project secret whose SHA-256 digest is this project's LangWatchQL
#   SQL tenant capability in ClickHouse. Deliberately NOT the API key: the
#   credential a caller authenticates with and the capability the database
#   resolves a tenant from stay decoupled, so rotating one never invalidates
#   the other, and a leak of the ClickHouse key map's input discloses nothing
#   a caller could authenticate with. Generated by the database on insert.
# kind:: Project kind:
#   - "application": user-facing workspace where developers send their
#   own app traces. The default for everything created via the
#   onboarding/quickstart flow.
#   - "internal_governance": hidden per-org routing/tenancy artifact
#   for IngestionSource ingest data. Auto-created lazily on the
#   first IngestionSource mint via ensureHiddenGovernanceProject().
#   MUST be filtered out of every user-visible Project surface
#   (project picker, /api/v1/projects, billing exports, RBAC
#   pickers, etc.) - the regression-test invariant in
#   specs/ai-gateway/governance/ui-contract.feature codifies this.
#   - "aggregate": a project that owns no traces and reads its member
#   projects through shared project-reader grants (ADR-177). Hidden
#   from every "send traces here" picker and from ingestion; visible in
#   the project switcher to organisation admins only.
#   Stored as a free-form string (matching IngestionSource.sourceType
#   pattern) so future routing kinds can ship without schema migrations.
# aggregateRule:: The scope rule an aggregate project materialises into grants. Null on
#   every other kind; decided in ADR-177. Shapes: { kind: "all-personal" } |
#   { kind: "personal-by-department", departmentId } |
#   { kind: "explicit", projectIds: string[] }.
# personalFeatures:: Per-feature unlock flags for personal projects only. Shape:
#   `{ evaluations: bool, datasets: bool, annotations: bool, automations: bool }`.
#   Empty `{}` (default) reads as all-false at the service layer -
#   existing rows pre-migration require no backfill. The bundle is
#   a UI/nav predicate, NOT an auth gate (the underlying tRPC
#   routers stay open even when the bundle is off; admin tooling +
#   offline migration scripts can still operate on the data).
#   Team / org-scope projects are not feature-gated - this column
#   is meaningful only when `isPersonal=true`.
# departmentId:: Department assignment for spend attribution (the project / agent
#   lens, used when a trace has no principal user). Accounting-only.
# langyEgressAllowlist:: Per-project Langy egress allow-list (ADR-076). A nullable JSON array of
#   host patterns (`["registry.npmjs.org", "*.internal.acme.com"]`) that the
#   project's Langy workers may reach outbound. The *presence* of the list is
#   the enforcement mode: null/absent ⇒ monitor-only (watch, never block);
#   non-empty ⇒ the worker's egress adapter restricts outbound to
#   floor ∪ this list. Enforced in the agent pod's egress adapter — NOT the
#   gateway — so it lives on the project, not the VirtualKey. Resolved by
#   LangyCredentialService.getEgressAllowlist and threaded through the
#   per-request credentials envelope. See specs/langy/langy-egress-enforcement.feature.
# lastCodingAgentSessionAt:: When a coding-agent session was last folded for this project, and when a
#   pull request was last mapped for a branch one of those sessions ran on.
#   Both are instrumentation signals, not counters: the project sidebar shows
#   its Sessions and Pull requests destinations only while the matching column
#   is inside the recency window, so a project that never sends coding-agent
#   telemetry never grows the two links, and one that stops sending loses
#   them again. Written through the throttled touch methods on
#   ProjectService, which skip the write while the stored value is still
#   recent, so a busy project costs at most one update an hour per column.
#   No index: every read is by project id, which is the primary key.
#   See specs/coding-agent/project-menu-links.feature.
class Project < ApplicationRecord
  self.table_name = "Project"
  self.implicit_order_column = "createdAt"

  attribute :id, default: -> { Nanoid.generate }
  attribute :kind, default: "application"
  attribute :firstMessage, default: false
  attribute :integrated, default: false
  attribute :traceSharingEnabled, default: true
  attribute :presenceEnabled, default: true
  attribute :isPersonal, default: false
  attribute :personalFeatures, default: -> { JSON.parse("{}") }
  alias_attribute :created_at, :createdAt
  alias_attribute :updated_at, :updatedAt

  validates :name, presence: true
  validates :slug, presence: true, uniqueness: true
  validates :apiKey, presence: true, uniqueness: true
  validates :lwqlKey, uniqueness: true
  validates :language, presence: true
  validates :framework, presence: true
  validates :ownerUserId, length: { maximum: 255 }

  belongs_to :team, foreign_key: "teamId", inverse_of: :projects
  belongs_to :owner_user, class_name: "User", foreign_key: "ownerUserId", optional: true, inverse_of: :personal_projects
  has_many :checks, class_name: "MonitorRecord", foreign_key: "projectId", inverse_of: :project,
                    dependent: :restrict_with_error
  has_many :costs, foreign_key: "projectId", inverse_of: :project, dependent: :restrict_with_error
  has_many :topics, foreign_key: "projectId", inverse_of: :project, dependent: :restrict_with_error
  has_many :datasets, foreign_key: "projectId", inverse_of: :project, dependent: :restrict_with_error
  has_many :dataset_records, foreign_key: "projectId", inverse_of: :project, dependent: :restrict_with_error
  has_many :custom_graphs, foreign_key: "projectId", inverse_of: :project, dependent: :restrict_with_error
  has_many :dashboards, foreign_key: "projectId", inverse_of: :project, dependent: :restrict_with_error
  has_many :batch_evaluations, foreign_key: "projectId", inverse_of: :project, dependent: :restrict_with_error
  has_many :triggers, foreign_key: "projectId", inverse_of: :project, dependent: :restrict_with_error
  has_many :experiments, foreign_key: "projectId", inverse_of: :project, dependent: :restrict_with_error
  has_many :annotations, foreign_key: "projectId", inverse_of: :project, dependent: :restrict_with_error
  has_many :project_secrets, foreign_key: "projectId", inverse_of: :project, dependent: :restrict_with_error
  has_many :trigger_sent, foreign_key: "projectId", inverse_of: :project, dependent: :restrict_with_error
  has_many :webhook_deliveries, class_name: "WebhookEndpointDelivery", foreign_key: "projectId", inverse_of: :project,
                                dependent: :destroy
  has_many :annotation_scores, foreign_key: "projectId", inverse_of: :project, dependent: :restrict_with_error
  has_many :share_links, foreign_key: "projectId", inverse_of: :project, dependent: :restrict_with_error
  has_many :workflows, foreign_key: "projectId", inverse_of: :project, dependent: :restrict_with_error
  has_many :workflow_version, foreign_key: "projectId", inverse_of: :project, dependent: :restrict_with_error
  has_many :annotation_queue, foreign_key: "projectId", inverse_of: :project, dependent: :restrict_with_error
  has_many :annotation_queue_item, foreign_key: "projectId", inverse_of: :project, dependent: :restrict_with_error
  has_many :llm_prompt_configs, foreign_key: "projectId", inverse_of: :project, dependent: :restrict_with_error
  has_many :analytics, class_name: "Analytics", foreign_key: "projectId", inverse_of: :project,
                       dependent: :restrict_with_error
  has_many :notifications, foreign_key: "projectId", inverse_of: :project, dependent: :destroy
  has_many :agents, foreign_key: "projectId", inverse_of: :project, dependent: :restrict_with_error
  has_many :evaluators, foreign_key: "projectId", inverse_of: :project, dependent: :restrict_with_error
  has_many :scenarios, foreign_key: "projectId", inverse_of: :project, dependent: :restrict_with_error
  has_many :suite_configurations, class_name: "SimulationSuite", foreign_key: "projectId", inverse_of: :project,
                                  dependent: :restrict_with_error
  has_many :saved_views, foreign_key: "projectId", inverse_of: :project, dependent: :restrict_with_error
  has_many :gateway_guardrails, foreign_key: "projectId", inverse_of: :project, dependent: :destroy
  has_many :gateway_change_events, foreign_key: "projectId", inverse_of: :project, dependent: :nullify
  has_many :pinned_traces, foreign_key: "projectId", inverse_of: :project, dependent: :restrict_with_error
  has_many :trace_edit_overlays, foreign_key: "projectId", inverse_of: :project, dependent: :restrict_with_error
  has_many :email_suppressions, foreign_key: "projectId", inverse_of: :project, dependent: :restrict_with_error
end
