defmodule Trigger.WebhookEndpoint do
  use Ecto.Schema

  @primary_key false
  @timestamps_opts [type: Trigger.PrismaDateTime, autogenerate: {Trigger.PrismaDateTime, :autogenerate, []}]

  @type t :: %__MODULE__{
          id: String.t(),
          friendly_id: String.t(),
          opaque_id: String.t(),
          organization_id: String.t(),
          project_id: String.t(),
          runtime_environment_id: String.t(),
          environment_type: atom(),
          endpoint_tenant_id: String.t(),
          endpoint_external_ref: String.t(),
          source: String.t(),
          declared_id: String.t(),
          routing_targets: map() | list() | String.t() | number() | boolean(),
          verifier_artifact: map() | list() | String.t() | number() | boolean(),
          metadata: map() | list() | String.t() | number() | boolean(),
          secret_provisioning: String.t(),
          setup_prompt: String.t() | nil,
          signing_secret_key: String.t() | nil,
          status: atom(),
          manually_deactivated_at: DateTime.t() | nil,
          inserted_at: DateTime.t(),
          updated_at: DateTime.t()
        }

  schema "WebhookEndpoint" do
    field(:id, :string, primary_key: true)
    field(:friendly_id, :string, source: :friendlyId)
    # URL key. CSPRNG, NOT a friendlyId: crypto.randomBytes(16) base64url.
    # Generated by the create path (deploy-sync / P2 API), NOT by @default.
    field(:opaque_id, :string, source: :opaqueId)
    field(:organization_id, :string, source: :organizationId)
    field(:project_id, :string, source: :projectId)
    field(:runtime_environment_id, :string, source: :runtimeEnvironmentId)
    field(:environment_type, Ecto.Enum, values: [:PRODUCTION, :STAGING, :DEVELOPMENT, :PREVIEW], source: :environmentType)
    field(:endpoint_tenant_id, :string, default: "", source: :endpointTenantId)
    field(:endpoint_external_ref, :string, default: "", source: :endpointExternalRef)
    field(:source, :string)
    # The declared webhooks.endpoint.define id (string ref, no relation).
    field(:declared_id, :string, source: :declaredId)
    # Subscribers of this endpoint: StoredWebhookRoutingTarget[] ({ id, type: "task" | "session", ..., filterAst }).
    field(:routing_targets, Trigger.PrismaJson, default: [], source: :routingTargets)
    field(:verifier_artifact, Trigger.PrismaJson, source: :verifierArtifact)
    field(:metadata, Trigger.PrismaJson, default: %{})
    field(:secret_provisioning, :string, default: "either", source: :secretProvisioning)
    # The source's instructions for an AI agent registering this endpoint with the provider.
    field(:setup_prompt, :string, source: :setupPrompt)
    # SecretReference.key string. Plain String, NO @relation -> no FK to SecretReference.
    field(:signing_secret_key, :string, source: :signingSecretKey)
    field(:status, Ecto.Enum, values: [:ACTIVE, :INACTIVE, :DELETING], default: :ACTIVE)
    # When an operator disabled the endpoint via the dashboard/API. Null means the declarative sync
    # owns the status: a redeploy that re-declares a previously-removed (auto-deactivated) webhook
    # reactivates it. Non-null means the operator disabled it, so the sync leaves the status alone.
    field(:manually_deactivated_at, Trigger.PrismaDateTime, source: :manuallyDeactivatedAt)
    timestamps(inserted_at_source: :createdAt, updated_at_source: :updatedAt)
  end
end