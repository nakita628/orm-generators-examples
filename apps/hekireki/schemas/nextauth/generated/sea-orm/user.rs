use super::prisma_date_time::PrismaDateTime;
use sea_orm::entity::prelude::*;
use serde::{Deserialize, Serialize};

#[derive(Clone, Debug, PartialEq, Eq, DeriveEntityModel, Serialize, Deserialize)]
#[sea_orm(table_name = "User")]
pub struct Model {
    #[sea_orm(primary_key, auto_increment = false)]
    #[sea_orm(column_type = "Text")]
    pub id: String,
    #[sea_orm(column_type = "Text")]
    pub name: Option<String>,
    #[sea_orm(unique)]
    #[sea_orm(column_type = "Text")]
    pub email: String,
    #[sea_orm(column_name = "emailVerified")]
    pub email_verified: Option<PrismaDateTime>,
    #[sea_orm(column_type = "Text")]
    pub image: Option<String>,
}

#[derive(Copy, Clone, Debug, EnumIter, DeriveRelation)]
pub enum Relation {
    #[sea_orm(has_many = "super::account::Entity")]
    Accounts,
    #[sea_orm(has_many = "super::session::Entity")]
    Sessions,
    #[sea_orm(has_many = "super::authenticator::Entity")]
    Authenticator,
}

impl Related<super::account::Entity> for Entity {
    fn to() -> RelationDef {
        Relation::Accounts.def()
    }
}

impl Related<super::session::Entity> for Entity {
    fn to() -> RelationDef {
        Relation::Sessions.def()
    }
}

impl Related<super::authenticator::Entity> for Entity {
    fn to() -> RelationDef {
        Relation::Authenticator.def()
    }
}

impl ActiveModelBehavior for ActiveModel {}
