package shelf.models

import org.jetbrains.exposed.v1.core.dao.id.EntityID
import org.jetbrains.exposed.v1.dao.Entity
import org.jetbrains.exposed.v1.dao.EntityBatchUpdate
import org.jetbrains.exposed.v1.dao.EntityClass
import java.time.Instant
import java.time.temporal.ChronoUnit

class ScanEntity(
    id: EntityID<String>,
) : Entity<String>(id) {
    companion object : EntityClass<String, ScanEntity>(ScanTable)

    var latitude by ScanTable.latitude
    var longitude by ScanTable.longitude
    var userAgent by ScanTable.userAgent
    var user by UserEntity optionalReferencedOn ScanTable.userId
    var userId by ScanTable.userId
    var qr by QrEntity optionalReferencedOn ScanTable.qrId
    var qrId by ScanTable.qrId
    var rawQrId by ScanTable.rawQrId
    var codeType by ScanTable.codeType
    var code by ScanTable.code
    var barcode by BarcodeEntity optionalReferencedOn ScanTable.barcodeId
    var barcodeId by ScanTable.barcodeId
    var asset by AssetEntity optionalReferencedOn ScanTable.assetId
    var assetId by ScanTable.assetId
    var kit by KitEntity optionalReferencedOn ScanTable.kitId
    var kitId by ScanTable.kitId
    var organization by OrganizationEntity referencedOn ScanTable.organizationId
    var organizationId by ScanTable.organizationId
    var source by ScanTable.source1
    var manuallyGenerated by ScanTable.manuallyGenerated
    var createdAt by ScanTable.createdAt
    var updatedAt by ScanTable.updatedAt

    override fun flush(batch: EntityBatchUpdate?): Boolean {
        if (writeValues.isNotEmpty()) {
            if (!isWritten(ScanTable.updatedAt)) {
                updatedAt = Instant.now().truncatedTo(ChronoUnit.MILLIS)
            }
        }
        return super.flush(batch)
    }
}
